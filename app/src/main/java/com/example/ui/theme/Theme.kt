private val DarkColorScheme =
  darkColorScheme(
    primary = DarkPrimary,
    secondary = DarkSecondary,
    tertiary = DarkTertiary,
    background = DarkBackground,
    surface = DarkSurface,
    onBackground = DarkOnBackground,
    onSurface = DarkOnSurface
  )

private val LightColorScheme = DarkColorScheme // Forzamos un tema oscuro consistente y uniforme para toda la app

@Composable
fun MyApplicationTheme(
  darkTheme: Boolean = true, // Forzamos darkTheme por defecto
  dynamicColor: Boolean = false, // Desactivamos colores dinámicos para mantener el branding premium naranja/verde Bitcoin
  content: @Composable () -> Unit,
) {
  val colorScheme = DarkColorScheme

  MaterialTheme(colorScheme = colorScheme, typography = Typography, content = content)
}
